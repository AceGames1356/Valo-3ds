/* 2D primitives and a built-in 5x7 uppercase font for column-major RGB565
   surfaces (the native 3DS framebuffer layout). */
#include "gfx.h"

void gx_clear(Surf s,uint16_t c){
    size_t n=(size_t)s.w*SCR_H;
    for(size_t i=0;i<n;i++) s.p[i]=c;
}

void gx_rect(Surf s,int x,int y,int w,int h,uint16_t c){
    int x1=x+w,y1=y+h;
    if(x<0){x=0;}
    if(y<0){y=0;}
    if(x1>s.w){x1=s.w;}
    if(y1>SCR_H){y1=SCR_H;}
    if(x>=x1||y>=y1) return;
    for(int xx=x;xx<x1;xx++){
        uint16_t *p=s.p+xx*SCR_H+(SCR_H-y1);
        for(int i=0;i<y1-y;i++) p[i]=c;
    }
}

void gx_rect_a(Surf s,int x,int y,int w,int h,uint16_t c,int a32){
    int x1=x+w,y1=y+h;
    if(a32<=0) return;
    if(a32>=32){ gx_rect(s,x,y,w,h,c); return; }
    if(x<0){x=0;}
    if(y<0){y=0;}
    if(x1>s.w){x1=s.w;}
    if(y1>SCR_H){y1=SCR_H;}
    for(int xx=x;xx<x1;xx++){
        uint16_t *p=s.p+xx*SCR_H+(SCR_H-y1);
        for(int i=0;i<y1-y;i++) p[i]=gx_blend(p[i],c,a32);
    }
}

void gx_frame(Surf s,int x,int y,int w,int h,uint16_t c){
    gx_rect(s,x,y,w,1,c); gx_rect(s,x,y+h-1,w,1,c);
    gx_rect(s,x,y,1,h,c); gx_rect(s,x+w-1,y,1,h,c);
}

void gx_line(Surf s,int x0,int y0,int x1,int y1,uint16_t c){
    int dx=x1>x0?x1-x0:x0-x1, sx=x0<x1?1:-1;
    int dy=-(y1>y0?y1-y0:y0-y1), sy=y0<y1?1:-1, err=dx+dy;
    for(int guard=0;guard<2000;guard++){
        gx_px(s,x0,y0,c);
        if(x0==x1&&y0==y1) break;
        int e=2*err;
        if(e>=dy){err+=dy;x0+=sx;}
        if(e<=dx){err+=dx;y0+=sy;}
    }
}

void gx_disc(Surf s,int cx,int cy,int r,uint16_t c){
    for(int y=-r;y<=r;y++)
        for(int x=-r;x<=r;x++)
            if(x*x+y*y<=r*r) gx_px(s,cx+x,cy+y,c);
}

