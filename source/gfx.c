int gx_textw(const char *t,int scale){ return (int)strlen(t)*6*scale - scale; }

void gx_text(Surf s,int x,int y,const char *t,uint16_t c,int scale){
    for(;*t;t++,x+=6*scale){
        int ch=(unsigned char)*t;
        if(ch>='a'&&ch<='z') ch-=32;
        if(ch<32||ch>95) ch=32;
        const uint8_t *g=FONT[ch-32];
        for(int col=0;col<5;col++){
            uint8_t bits=g[col];
            for(int row=0;row<7;row++)
                if(bits&(1<<row)){
                    if(scale==1) gx_px(s,x+col,y+row,c);
                    else gx_rect(s,x+col*scale,y+row*scale,scale,scale,c);
                }
        }
    }
}
void gx_textc(Surf s,int cx,int y,const char *t,uint16_t c,int scale){ gx_text(s,cx-gx_textw(t,scale)/2,y,t,c,scale); }
void gx_textr(Surf s,int rx,int y,const char *t,uint16_t c,int scale){ gx_text(s,rx-gx_textw(t,scale),y,t,c,scale); }
void gx_texts(Surf s,int x,int y,const char *t,uint16_t c,int scale){
    gx_text(s,x+scale,y+scale,t,RGB(0,0,0),scale);
    gx_text(s,x,y,t,c,scale);
}
